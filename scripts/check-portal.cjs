// A small check of the actual query, mock transport and platform opening paths.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
const { emptyFilters, queryReports, volume, descendants, breadcrumb, safeUrl, searchCatalog } = require('../src/lib/portal-model.ts');
const { reports, bootstrap } = require('../src/lib/portal-fixtures.ts');
const { mockRequest } = require('../src/lib/portal-mock.ts');
const query = (q = '', filters = emptyFilters(), page = 1) => queryReports(reports, { q, filters, page, pageSize: 6 });
assert.equal(query(' ROI ').items[0].module, '电商');
assert(query('张兆').items.every(r => r.owner === '张兆'));
assert(query('EBS').items.every(r => r.source.includes('EBS')));
assert.equal(query('没有这个报表').total, 0);
const filters = { ...emptyFilters(), module: ['供应链', '财务管理'], status: ['active'], frequency: ['T+1'] };
assert(query('', filters).items.every(r => filters.module.includes(r.module) && r.status === 'active' && r.frequency === 'T+1'));
assert.equal(query('').items.length, 6);
assert.notEqual(query('', emptyFilters(), 2).items[0].id, query('').items[0].id);
assert.deepEqual([99,100,1000,1001].map(volume), ['low','medium','medium','high']);
const supply = query('', { ...emptyFilters(), module: ['供应链'] });
assert.equal(supply.facets.module.find(v => v.value === '财务管理').count, reports.filter(r => r.module === '财务管理').length);
assert.deepEqual(breadcrumb(bootstrap.entries, 'region', 'topics').map(e => e.id), ['health','sales','region']);
assert(descendants(bootstrap.entries, 'health').some(e => e.id === 'entry-8'));
assert(!descendants(bootstrap.entries, 'health').some(e => e.id === 'entry-12'));
assert.equal(descendants([{ id:'a',parentId:'b' },{ id:'b',parentId:'a' }], 'a').length, 1);
const initial = mockRequest('/bootstrap').favoriteIds;
assert.equal(mockRequest('/favorites/entry-1', { favorite:true }).report.id, 'entry-1');
mockRequest('/favorites/entry-1', { favorite:true });
assert.equal(mockRequest('/bootstrap').favoriteIds.filter(id => id === 'entry-1').length, 1);
assert(mockRequest('/workbench?tab=favorites').items.some(r => r.id === 'entry-1'));
mockRequest('/favorites/entry-1', { favorite:false });
assert.deepEqual(mockRequest('/bootstrap').favoriteIds, initial);
assert.throws(() => mockRequest('/favorites/missing', { favorite:true }));
assert.throws(() => mockRequest('/favorites/entry-1', { favorite:'yes' }));
assert.throws(() => safeUrl('javascript:alert(1)'));
assert.throws(() => safeUrl('data:text/html,unsafe'));
const recent = mockRequest('/workbench?tab=recent').items;
assert(recent.every((r, i) => !i || r.lastVisitedOn <= recent[i-1].lastVisitedOn));
const frequent = mockRequest('/workbench?tab=frequent').items;
assert(frequent.every((r,i) => !i || r.visits30d <= frequent[i-1].visits30d));
assert.equal(mockRequest('/reports?q=ROI').total, 1);
assert.equal(mockRequest('/notices?pageSize=5').items.length, 5);
assert(searchCatalog(reports, 'report', '').items.every(item => item.report.status === 'active'));
assert.equal(searchCatalog(reports, 'metric', 'roi').items[0].value, 'ROI');
assert.equal(searchCatalog(reports.filter(r=>r.module==='临床经营'), 'tag', '财务').total, 0);
assert(queryReports(reports, {q:'供应链',category:'tag',filters:emptyFilters(),page:1,pageSize:100}).items.every(r=>r.module==='供应链'));
mockRequest('/search-history', {category:'metric',query:' ROI '});
assert.equal(mockRequest('/search-history', {category:'metric',query:'roi'}).items.length, 1);
assert.equal(mockRequest('/search-history?category=report').items.length, 0);
assert.equal(mockRequest('/search-history?category=metric', undefined, 'DELETE').items.length, 0);
process.env.NEXT_PUBLIC_PORTAL_MODE = 'api';
